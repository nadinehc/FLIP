#!/usr/bin/env python
"""
Runs the full vanilla-FLIP vs FLIP+G comparison unattended.

Pipeline, for the Table 1 main CIFAR-10 setting (ResNet-32, 1xs sinusoidal
trigger, source 9 -> target 4):

  1. Train N expert trajectories once. Experts are trained on the
     traditionally backdoored dataset and do not depend on the generator, so
     every setting below reuses the same checkpoints.
  2. For each setting -- the label-only baseline plus one run per epsilon --
     optimize the labels (and, for FLIP+G, the generator) and select flips at
     each budget m.
  3. For each (setting, m), train a user model and record CTA / PTA, then run
     the kmeans / PCA / SPECTRE defenses against the poisoned dataset.
  4. Write results.csv, results.md, and per-step stdout logs.

The baseline path invokes the untouched `generate_labels` / `train_user`
modules; only FLIP+G settings touch the new `*_noise` modules.

Every step is skipped if its outputs already exist, so an interrupted sweep can
be resumed by re-running the same command. Use --force to recompute.

Examples:
    python sweep/run_sweep.py --tag main
    python sweep/run_sweep.py --tag smoke --smoke
    python sweep/run_sweep.py --tag main --dry-run
"""

import argparse
import csv
import json
import os
import subprocess
import sys
import time
from datetime import timedelta
from pathlib import Path

import numpy as np
import toml


REPO_ROOT = Path(__file__).resolve().parent.parent

# Table 1 main CIFAR-10 setting.
BASE_SETTING = {
    'model': 'r32p',
    'dataset': 'cifar',
    'trainer': 'sgd',
    'poisoner': '1xs',
    'source_label': 9,
    'target_label': 4,
}

DEFAULT_BUDGETS = [150, 300, 500, 1000, 1500]

# Epsilon grid in 1/255 units. 16/255 is plainly visible on 32x32 CIFAR images
# and undercuts the premise of a subtle addition to a label-only attack, so the
# grid stops at 8/255 and adds 1/255 as a near-null reference point. Override
# with --epsilons.
DEFAULT_EPSILONS = [1, 2, 4, 8]

DEFENSES = ['kmeans', 'pca', 'spectre']


def log(msg):
    print(f"[sweep {time.strftime('%H:%M:%S')}] {msg}", flush=True)


class Runner:
    def __init__(self, args):
        self.args = args
        self.tag = args.tag
        self.out_root = REPO_ROOT / 'out' / 'sweep' / self.tag
        self.log_dir = self.out_root / 'logs'
        self.ckpt_dir = self.out_root / 'checkpoints'
        self.failures = []

        if not args.dry_run:
            self.log_dir.mkdir(parents=True, exist_ok=True)

    # -- plumbing ---------------------------------------------------------

    def write_config(self, exp_name, config):
        '''Writes an experiment config.toml that run_experiment.py can consume.'''
        exp_dir = REPO_ROOT / 'experiments' / exp_name
        if self.args.dry_run:
            log(f"would write {exp_dir / 'config.toml'}")
            return exp_dir

        exp_dir.mkdir(parents=True, exist_ok=True)
        with open(exp_dir / 'config.toml', 'w') as f:
            f.write(f"# Generated by sweep/run_sweep.py (tag={self.tag}).\n")
            f.write("# Edits here are overwritten on the next sweep run.\n\n")
            toml.dump(config, f)
        return exp_dir

    def run_experiment(self, exp_name, step_name, expect=None):
        """
        Runs one experiment, skipping it when its outputs are already present.

        Returns True on success. A failure is recorded and reported at the end
        rather than aborting, so one bad cell does not cost the whole sweep.
        """
        if expect and not self.args.force and all(Path(p).exists() for p in expect):
            log(f"skip {step_name} (outputs present)")
            return True

        log_path = self.log_dir / f"{step_name}.log"
        cmd = [self.args.python, 'run_experiment.py', exp_name]

        if self.args.dry_run:
            log(f"would run {' '.join(cmd)}  > {log_path}")
            return True

        log(f"run {step_name} -> {log_path}")
        start = time.time()
        with open(log_path, 'w') as f:
            f.write(f"$ {' '.join(cmd)}\n\n")
            f.flush()
            proc = subprocess.run(cmd, cwd=REPO_ROOT, stdout=f,
                                  stderr=subprocess.STDOUT)

        elapsed = timedelta(seconds=int(time.time() - start))
        if proc.returncode != 0:
            log(f"FAILED {step_name} (exit {proc.returncode}, {elapsed}) "
                f"-- see {log_path}")
            self.failures.append(step_name)
            return False

        log(f"done {step_name} ({elapsed})")
        return True

    # -- stage 1: experts -------------------------------------------------

    def expert_paths(self):
        '''Format strings that the label modules use to find checkpoints.'''
        rel = os.path.relpath(self.ckpt_dir, REPO_ROOT)
        return (f"{rel}/{{}}/model_{{}}_{{}}.pth",
                f"{rel}/{{}}/model_{{}}_{{}}_opt.pth")

    def train_experts(self):
        log(f"stage 1: {self.args.experts} expert trajectories")
        for i in range(self.args.experts):
            exp_name = f"sweep_{self.tag}_expert_{i}"
            out_dir = os.path.relpath(self.ckpt_dir / str(i), REPO_ROOT) + '/'

            config = {'train_expert': {
                'output_dir': out_dir,
                'model': BASE_SETTING['model'],
                'trainer': BASE_SETTING['trainer'],
                'dataset': BASE_SETTING['dataset'],
                'source_label': BASE_SETTING['source_label'],
                'target_label': BASE_SETTING['target_label'],
                'poisoner': BASE_SETTING['poisoner'],
                'epochs': self.args.expert_epochs,
                'checkpoint_iters': self.args.checkpoint_iters,
            }}
            self.write_config(exp_name, config)

            # The last checkpoint of the last epoch is the marker for "done".
            last = (self.ckpt_dir / str(i) /
                    f"model_{self.args.expert_epochs}_"
                    f"{self.args.checkpoint_iters}.pth")
            self.run_experiment(exp_name, f"expert_{i}", expect=[last])

    # -- stage 2: labels (+ generator) and flip selection -----------------

    def settings(self):
        '''The baseline plus one FLIP+G setting per epsilon.'''
        yield {'name': 'vanilla', 'noise': False, 'eps_255': None}
        for eps in self.args.epsilons:
            yield {'name': f'noise_eps{eps}', 'noise': True, 'eps_255': eps}

    @staticmethod
    def parse_setting(name):
        '''Rebuilds a setting dict from an experiment directory's name.'''
        if name == 'vanilla':
            return {'name': name, 'noise': False, 'eps_255': None}
        if name.startswith('noise_eps'):
            try:
                return {'name': name, 'noise': True,
                        'eps_255': int(name[len('noise_eps'):])}
            except ValueError:
                return None
        return None

    def result_cells(self):
        '''
        Every (setting, m) cell worth collecting: the ones this invocation was
        asked to run, plus every one already on disk under this tag.

        collect() must not be limited to --epsilons / --budgets. write_results
        truncates results.csv, so running the sweep for one new epsilon would
        otherwise rewrite the table without the rows it was not asked for,
        dropping finished cells. The raw outputs survive, but the collected
        results silently lose them.
        '''
        cells = {}
        for setting in self.settings():
            for budget in self.args.budgets:
                cells[(setting['name'], budget)] = (setting, budget)

        prefix = f"sweep_{self.tag}_user_"
        for d in (REPO_ROOT / 'experiments').glob(prefix + '*_m*'):
            name, _, budget = d.name[len(prefix):].rpartition('_m')
            setting = self.parse_setting(name)
            if setting is None or not budget.isdigit():
                continue
            cells.setdefault((name, int(budget)), (setting, int(budget)))

        # Baseline first, then ascending epsilon, then ascending m, so the
        # table reads as a sweep regardless of what order cells were run in.
        return sorted(cells.values(),
                      key=lambda c: (c[0]['eps_255'] is not None,
                                     c[0]['eps_255'] or 0, c[1]))

    def attack_dir(self, setting):
        return REPO_ROOT / 'experiments' / f"sweep_{self.tag}_attack_{setting['name']}"

    def generate_labels(self, setting):
        exp_name = f"sweep_{self.tag}_attack_{setting['name']}"
        out_dir = os.path.relpath(self.attack_dir(setting), REPO_ROOT) + '/'
        input_pths, opt_pths = self.expert_paths()

        module = 'generate_labels_noise' if setting['noise'] else 'generate_labels'

        block = {
            'input_pths': input_pths,
            'opt_pths': opt_pths,
            'expert_model': BASE_SETTING['model'],
            'trainer': BASE_SETTING['trainer'],
            'dataset': BASE_SETTING['dataset'],
            'source_label': BASE_SETTING['source_label'],
            'target_label': BASE_SETTING['target_label'],
            'poisoner': BASE_SETTING['poisoner'],
            'output_dir': out_dir,
            'lambda': 0.0,
            # `max` is capped at the number of epochs actually checkpointed:
            # extract_experts samples a trajectory epoch in [1, max], and
            # asking for an epoch past the end of training is a
            # FileNotFoundError at the first batch.
            'expert_config': {
                'experts': self.args.experts,
                'min': 0,
                'max': min(15, self.args.expert_epochs),
            },
            'attack_config': {
                'iterations': self.args.attack_iterations,
                'one_hot_temp': 5,
                'label_kwargs': {'lr': 150, 'momentum': 0.5},
            },
        }

        if setting['noise']:
            block['use_image_noise'] = True
            block['noise_config'] = {
                'epsilon_255': setting['eps_255'],
                'norm': self.args.norm,
                'width': self.args.generator_width,
                'lr': self.args.generator_lr,
                'warmup': self.args.generator_warmup,
                'quantize': True,
            }

        config = {module: block}

        # select_flips consumes the labels in the same experiment.
        config['select_flips'] = {
            'budgets': self.args.budgets,
            'input_label_glob': out_dir + 'labels.npy',
            'true_labels': out_dir + 'true.npy',
            'output_dir': out_dir,
        }

        self.write_config(exp_name, config)

        expect = [self.attack_dir(setting) / f"{m}.npy" for m in self.args.budgets]
        if setting['noise']:
            expect.append(self.attack_dir(setting) / 'generator.pth')
        return self.run_experiment(exp_name, f"attack_{setting['name']}",
                                   expect=expect)

    # -- stage 3: user model and defenses ---------------------------------

    def user_dir(self, setting, budget):
        return (REPO_ROOT / 'experiments' /
                f"sweep_{self.tag}_user_{setting['name']}_m{budget}")

    def train_user_and_defend(self, setting, budget):
        exp_name = f"sweep_{self.tag}_user_{setting['name']}_m{budget}"
        attack_dir = os.path.relpath(self.attack_dir(setting), REPO_ROOT) + '/'
        out_dir = os.path.relpath(self.user_dir(setting, budget), REPO_ROOT) + '/'
        generator = attack_dir + 'generator.pth' if setting['noise'] else None

        module = 'train_user_noise' if setting['noise'] else 'train_user'
        block = {
            'input_labels': f"{attack_dir}{budget}.npy",
            'true_labels': f"{attack_dir}true.npy",
            'user_model': BASE_SETTING['model'],
            'trainer': BASE_SETTING['trainer'],
            'dataset': BASE_SETTING['dataset'],
            'source_label': BASE_SETTING['source_label'],
            'target_label': BASE_SETTING['target_label'],
            'poisoner': BASE_SETTING['poisoner'],
            'output_dir': out_dir,
            'soft': False,
            'alpha': 0.0,
        }
        if self.args.user_epochs is not None:
            block['epochs'] = self.args.user_epochs
        if self.args.user_milestones is not None:
            block['scheduler_kwargs'] = {'milestones': self.args.user_milestones}
        if setting['noise']:
            block['generator'] = generator

        config = {module: block}
        config['run_defenses'] = {
            'model_pth': out_dir + 'model.pth',
            'input_labels': f"{attack_dir}{budget}.npy",
            'true_labels': f"{attack_dir}true.npy",
            'output_dir': out_dir,
            'model': BASE_SETTING['model'],
            'dataset': BASE_SETTING['dataset'],
            'target_label': BASE_SETTING['target_label'],
            'defenses': DEFENSES,
            'expansion': self.args.expansion,
        }
        if setting['noise']:
            config['run_defenses']['generator'] = generator

        self.write_config(exp_name, config)

        expect = [self.user_dir(setting, budget) / 'caccs.npy',
                  self.user_dir(setting, budget) / 'defenses.json']
        return self.run_experiment(exp_name,
                                   f"user_{setting['name']}_m{budget}",
                                   expect=expect)

    # -- results ----------------------------------------------------------

    def collect(self):
        '''Reads every finished cell into a list of flat result rows.'''
        rows = []
        for setting, budget in self.result_cells():
            d = self.user_dir(setting, budget)
            row = {
                'setting': setting['name'],
                'attack': 'FLIP' if not setting['noise'] else 'FLIP+G',
                'epsilon_255': setting['eps_255'],
                'norm': self.args.norm if setting['noise'] else '',
                'm': budget,
            }

            try:
                caccs = np.load(d / 'caccs.npy')
                paccs = np.load(d / 'paccs.npy')
                row['cta'] = float(caccs[-1][0])
                row['pta'] = float(paccs[-1][0])
            except (FileNotFoundError, IndexError):
                row['cta'] = row['pta'] = None

            stats_path = d / 'noise_stats.json'
            if stats_path.exists():
                with open(stats_path) as f:
                    stats = json.load(f)
                row['n_flipped'] = stats.get('n_flipped')
                row['linf_max_255'] = stats.get('linf_max_255')
            else:
                row['n_flipped'] = None
                row['linf_max_255'] = None

            def_path = d / 'defenses.json'
            if def_path.exists():
                with open(def_path) as f:
                    defenses = json.load(f)
                row['n_poison_in_target'] = defenses.get('n_poison_in_target')
                # The baseline runs through `train_user`, which writes no
                # noise_stats.json, so take its flip count from here.
                if row['n_flipped'] is None:
                    row['n_flipped'] = defenses.get('n_flipped_total')
                for name in DEFENSES:
                    m = defenses['defenses'].get(name, {})
                    row[f'{name}_detect'] = m.get('detection_rate')
                    row[f'{name}_fpr'] = m.get('false_positive_rate')
                    row[f'{name}_auroc'] = m.get('auroc')
            else:
                row['n_poison_in_target'] = None
                for name in DEFENSES:
                    row[f'{name}_detect'] = None
                    row[f'{name}_fpr'] = None
                    row[f'{name}_auroc'] = None

            rows.append(row)
        return rows

    def write_results(self, rows):
        fields = ['setting', 'attack', 'epsilon_255', 'norm', 'm', 'cta', 'pta',
                  'n_flipped', 'linf_max_255', 'n_poison_in_target']
        for name in DEFENSES:
            fields += [f'{name}_detect', f'{name}_fpr', f'{name}_auroc']

        csv_path = self.out_root / 'results.csv'
        with open(csv_path, 'w', newline='') as f:
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            for row in rows:
                writer.writerow(row)

        def fmt(v, pct=False, places=3):
            if v is None:
                return '--'
            if pct:
                return f"{100 * v:.2f}"
            return f"{v:.{places}f}"

        md_path = self.out_root / 'results.md'
        with open(md_path, 'w') as f:
            f.write(f"# FLIP vs FLIP+G sweep (`{self.tag}`)\n\n")
            f.write(f"- Setting: {BASE_SETTING['dataset']}, "
                    f"{BASE_SETTING['model']}, trigger `{BASE_SETTING['poisoner']}`, "
                    f"source {BASE_SETTING['source_label']} -> "
                    f"target {BASE_SETTING['target_label']}\n")
            f.write(f"- Experts: {self.args.experts} x {self.args.expert_epochs} "
                    f"epochs; attack iterations: {self.args.attack_iterations}\n")
            f.write(f"- Perturbation: {self.args.norm} bound, applied to flipped "
                    f"examples only, baked in as 8-bit images before the "
                    f"victim's augmentation\n")
            f.write(f"- Defenses given a {self.args.expansion}x removal budget "
                    f"over the true poison count; detection rate is the share "
                    f"of real poisons removed\n")
            f.write("- CTA / PTA in %, detection / FPR in %, AUROC in [0, 1]\n")
            f.write("- Defense implementations are reimplementations; see "
                    "`modules/run_defenses/utils.py`\n\n")

            f.write("| attack | eps (/255) | m | CTA | PTA | "
                    "kmeans det | kmeans AUROC | PCA det | PCA AUROC | "
                    "SPECTRE det | SPECTRE AUROC | realized Linf (/255) |\n")
            f.write("|---|---|---|---|---|---|---|---|---|---|---|---|\n")
            for row in rows:
                f.write(
                    f"| {row['attack']} "
                    f"| {row['epsilon_255'] if row['epsilon_255'] else '--'} "
                    f"| {row['m']} "
                    f"| {fmt(row['cta'], pct=True)} "
                    f"| {fmt(row['pta'], pct=True)} "
                    f"| {fmt(row['kmeans_detect'], pct=True)} "
                    f"| {fmt(row['kmeans_auroc'])} "
                    f"| {fmt(row['pca_detect'], pct=True)} "
                    f"| {fmt(row['pca_auroc'])} "
                    f"| {fmt(row['spectre_detect'], pct=True)} "
                    f"| {fmt(row['spectre_auroc'])} "
                    f"| {fmt(row['linf_max_255'], places=2)} |\n"
                )

            if self.failures:
                f.write(f"\n## Failed steps ({len(self.failures)})\n\n")
                for name in self.failures:
                    f.write(f"- `{name}` -- see `logs/{name}.log`\n")

        log(f"wrote {csv_path}")
        log(f"wrote {md_path}")

    # -- preflight --------------------------------------------------------

    def preflight(self):
        """
        Checks the chosen interpreter can actually run a module.

        Without this, launching with the wrong interpreter -- a conda env that
        was never activated, say -- burns one failed step per cell before
        anything says why.
        """
        probe = ("import torch;"
                 "print(torch.__version__, torch.cuda.is_available())")
        proc = subprocess.run([self.args.python, '-c', probe],
                              cwd=REPO_ROOT, capture_output=True, text=True)

        if proc.returncode != 0:
            log(f"PREFLIGHT FAILED: {self.args.python} cannot import torch")
            for line in proc.stderr.strip().splitlines()[-3:]:
                log(f"  {line}")
            log("activate the project environment first, or pass --python "
                "/path/to/env/bin/python")
            return False

        version, cuda = proc.stdout.strip().split()
        log(f"preflight: torch {version}, cuda available: {cuda}")
        if cuda != 'True':
            log("WARNING: no CUDA device visible -- load_model() calls .cuda() "
                "and every step will fail. Request a GPU allocation.")
            return False
        return True

    def check_experts(self):
        """
        Verifies the expert checkpoints the attack will be told to sample from
        actually exist.

        `--skip-experts` skips stage 1 but leaves `--experts` at its default,
        so the attack config can announce more trajectories than are on disk.
        `extract_experts` then samples an index with no checkpoint and dies
        with a bare FileNotFoundError seconds into stage 2, after the sweep has
        already reported stage 1 as handled. Checking here names the real
        problem instead.
        """
        missing = []
        for i in range(self.args.experts):
            last = (self.ckpt_dir / str(i) /
                    f"model_{self.args.expert_epochs}_"
                    f"{self.args.checkpoint_iters}.pth")
            if not last.exists():
                missing.append(i)
        if not missing:
            log(f"experts: {self.args.experts} trajectories present "
                f"({self.args.expert_epochs} epochs each)")
            return True

        shown = ', '.join(str(i) for i in missing[:8])
        log(f"EXPERT CHECK FAILED: {len(missing)} of {self.args.experts} "
            f"expert trajectories have no final checkpoint under "
            f"{self.ckpt_dir} (missing: {shown}"
            f"{', ...' if len(missing) > 8 else ''})")
        present = sum(1 for i in range(self.args.experts)
                      if i not in set(missing))
        log(f"the attack would sample from {self.args.experts} trajectories "
            f"but only {present} are on disk, and sampling a missing one is a "
            f"FileNotFoundError in stage 2")
        log(f"pass --experts <n> matching what was trained (and the same "
            f"--expert-epochs {self.args.expert_epochs} / --checkpoint-iters "
            f"{self.args.checkpoint_iters}), or drop --skip-experts to train "
            f"the rest")
        return False

    # -- cost -------------------------------------------------------------

    def estimate(self):
        """
        Rough cost in 'epoch-equivalents': one pass over CIFAR-10 with this
        architecture.

        A trajectory-matching iteration costs roughly 4 normal epochs -- per
        batch it runs an expert step, a student step, and a double-backward
        through the student's gradient. That factor is a stand-in, not a
        measurement, so treat the total as an order of magnitude.
        """
        n_settings = 1 + len(self.args.epsilons)
        user_epochs = self.args.user_epochs or 200   # DEFAULT_SGD_EPOCHS

        experts = self.args.experts * self.args.expert_epochs
        attacks = n_settings * self.args.attack_iterations * 4
        users = n_settings * len(self.args.budgets) * user_epochs

        return {
            'experts': experts,
            'attacks': attacks,
            'users': users,
            'total': experts + attacks + users,
            'n_user_models': n_settings * len(self.args.budgets),
        }

    def log_estimate(self):
        e = self.estimate()
        log(f"cost estimate: {e['total']} epoch-equivalents "
            f"({e['experts']} experts + ~{e['attacks']} attack + "
            f"{e['users']} user, over {e['n_user_models']} user models)")

        spe = self.args.seconds_per_epoch
        if spe:
            hours = e['total'] * spe / 3600
            log(f"at {spe:.1f} s/epoch that is ~{hours:.1f} h wall clock")
        else:
            log("pass --seconds-per-epoch (from the first expert's log) "
                "for a wall-clock figure")

    # -- driver -----------------------------------------------------------

    def run(self):
        start = time.time()
        log(f"sweep tag={self.tag}  epsilons={self.args.epsilons} (/255)  "
            f"budgets={self.args.budgets}")
        log(f"outputs under {self.out_root}")

        if not self.args.dry_run and not self.args.skip_preflight:
            if not self.preflight():
                log("aborting before any step ran")
                return 2

        self.log_estimate()

        if not self.args.skip_experts:
            self.train_experts()
        else:
            log("stage 1: skipped (--skip-experts)")

        if not self.args.dry_run and not self.check_experts():
            log("aborting before stage 2")
            return 2

        log("stage 2: label optimization and flip selection")
        ready = []
        for setting in self.settings():
            if self.generate_labels(setting):
                ready.append(setting)
            else:
                log(f"skipping downstream steps for {setting['name']}")

        log("stage 3: user models and defenses")
        for setting in ready:
            for budget in self.args.budgets:
                self.train_user_and_defend(setting, budget)

        if self.args.dry_run:
            log("dry run complete; no results to collect")
            return 0

        log("collecting results")
        self.write_results(self.collect())

        elapsed = timedelta(seconds=int(time.time() - start))
        if self.failures:
            log(f"sweep finished in {elapsed} with {len(self.failures)} "
                f"failed step(s): {', '.join(self.failures)}")
            return 1
        log(f"sweep finished in {elapsed}; all steps succeeded")
        return 0


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument('--tag', default='main',
                   help="Names the output directory and experiment configs.")
    p.add_argument('--python', default=sys.executable,
                   help="Interpreter used to run each module.")

    p.add_argument('--epsilons', type=int, nargs='+', default=DEFAULT_EPSILONS,
                   help="Epsilon grid in 1/255 units.")
    p.add_argument('--budgets', type=int, nargs='+', default=DEFAULT_BUDGETS,
                   help="Label-flip budgets m.")
    p.add_argument('--norm', choices=['linf', 'l2'], default='linf',
                   help="Norm the perturbation is bounded in.")

    p.add_argument('--experts', type=int, default=50,
                   help="Number of expert trajectories (repo default: 50).")
    p.add_argument('--expert-epochs', type=int, default=20,
                   help="Epochs per expert.")
    p.add_argument('--checkpoint-iters', type=int, default=50,
                   help="Iterations between expert checkpoints.")
    p.add_argument('--attack-iterations', type=int, default=15,
                   help="Trajectory-matching iterations (repo default: 15).")
    p.add_argument('--user-epochs', type=int, default=None,
                   help="Epochs for each user model. Trainer default if unset.")
    p.add_argument('--user-milestones', type=int, nargs='+', default=None,
                   help="LR decay epochs for the user model. The trainer "
                        "default is [75, 125], tuned for a 200-epoch run; "
                        "shorten this alongside --user-epochs or the model "
                        "trains most of its run at the initial LR.")
    p.add_argument('--seconds-per-epoch', type=float, default=None,
                   help="Measured epoch time, used to turn the printed cost "
                        "estimate into a wall-clock figure.")

    p.add_argument('--generator-width', type=int, default=32,
                   help="Base channel count of G.")
    p.add_argument('--generator-lr', type=float, default=1e-3,
                   help="Adam learning rate for G.")
    p.add_argument('--generator-warmup', type=int, default=0,
                   help="Label-only iterations before G starts training.")

    p.add_argument('--expansion', type=float, default=1.5,
                   help="Defense removal budget, as a multiple of the poison count.")

    p.add_argument('--skip-experts', action='store_true',
                   help="Reuse checkpoints already under out/sweep/<tag>/checkpoints.")
    p.add_argument('--force', action='store_true',
                   help="Recompute steps even when their outputs exist.")
    p.add_argument('--dry-run', action='store_true',
                   help="Write configs and print the plan without running.")
    p.add_argument('--skip-preflight', action='store_true',
                   help="Skip the torch/CUDA check before the first step.")
    p.add_argument('--collect-only', action='store_true',
                   help="Only re-read finished cells and rewrite the tables.")

    p.add_argument('--smoke', action='store_true',
                   help="Tiny end-to-end run to verify the pipeline.")

    args = p.parse_args(argv)

    if args.smoke:
        args.experts = 1
        args.expert_epochs = 2
        args.attack_iterations = 1
        args.user_epochs = 2
        args.budgets = [150]
        args.epsilons = [8]

    return args


def main(argv=None):
    args = parse_args(argv)
    runner = Runner(args)

    if args.collect_only:
        runner.write_results(runner.collect())
        return 0
    return runner.run()


if __name__ == '__main__':
    sys.exit(main())
